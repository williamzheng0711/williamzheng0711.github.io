import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { validateVisited, encodeVisited, decodeVisited } from '../packages/journeysphere/src/state.js';
import assert from 'node:assert/strict';

const root = new URL('../', import.meta.url);
const read = path => JSON.parse(readFileSync(new URL(path, root), 'utf8'));
const catalog = read('packages/journeysphere/data/catalog.json');
const record = read('data/journeysphere-visits.json');
assert.equal(record.atlasVersion, catalog.version, 'Homepage travel record must pin the atlas version');
validateVisited(record.visited, catalog);
assert.deepEqual(new Set(decodeVisited(encodeVisited(record.visited, catalog), catalog)), new Set(record.visited));
const html = readFileSync(new URL('index.html', root), 'utf8');
const adapter = readFileSync(new URL('JS/site.js', root), 'utf8');
assert.match(html, /type="module" src="JS\/site.js"/);
assert.match(adapter, /import \{ createJourneySphere, loadAtlas \} from '\.\.\/packages\/journeysphere\/src\/index.js'/);
assert.doesNotMatch(adapter, /L\.geoJSON|L\.map\(/, 'Homepage must consume the package, not duplicate its renderer');
execFileSync(process.execPath, ['scripts/validate-atlas.mjs'], { cwd: new URL('packages/journeysphere/', root), stdio: 'inherit' });
execFileSync('npm', ['test'], { cwd: new URL('packages/journeysphere/', root), stdio: 'inherit' });
console.log(`Homepage integration verified: ${record.visited.length} stable region IDs, version-bound state, package renderer.`);
